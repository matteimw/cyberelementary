const esc = (s) => String(s == null ? "" : s)
  .replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
const slugify = (t) => (t || "").toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/(^-|-$)/g, "");

function unitsWithLessons(C) {
  return C.units.map((u, i) => {
    const [a, b] = u.lessons.split("-").map(Number);
    return { ...u, num: i + 1, from: a, to: b, lessons: C.lessons.filter((l) => l.n >= a && l.n <= b) };
  });
}

function videoHref(D, l) {
  if (!l.videoId) return "";
  const v = D.videos.find((x) => x.id === l.videoId);
  return v ? `videos.html#${v.id}-${slugify(v.title)}` : `https://www.youtube.com/watch?v=${l.videoId}`;
}

function findBook(D, re) {
  const b = D.books.find((x) => re.test(x.title));
  return b ? { title: b.title, href: D.amazonLink(b.amazon) } : null;
}

function books(D, g) {
  return {
    plan: findBook(D, new RegExp(`${ORD[g]} Grade Lesson Plan Book`, "i")),
    workbook: findBook(D, new RegExp(`${ORD[g]} Grade Skills Workbook`, "i")),
    complete: findBook(D, /Complete Lesson Plan Book/i),
  };
}

