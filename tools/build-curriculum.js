/* ---------------- Entry point ---------------- */

module.exports = function buildCurriculum(ROOT, D) {
  const C = D.curriculum;
  if (!C || !C.lessons || !C.lessons.length) return { pages: [], published: false };
  const draft = !C.published;
  const out = [["curriculum.html", overviewPage(D, C, draft)]];

  for (const [file, html] of out) {
    const p = path.join(ROOT, file);
    // Keep the already-prerendered header/footer so re-runs are stable:
    // write only when the generated source differs from the last build.
    const stamp = `<!-- source-hash:${require("crypto").createHash("sha1").update(html).digest("hex").slice(0, 12)} -->`;
    const existing = fs.existsSync(p) ? fs.readFileSync(p, "utf8") : "";
    if (!existing.includes(stamp)) fs.writeFileSync(p, html.replace("<body>", `<body>\n${stamp}`));
  }
  return { pages: out.map(([f]) => f), published: !draft, faq: faqItems(C) };
};
